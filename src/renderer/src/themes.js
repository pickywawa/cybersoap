export function applyTheme(name, { scanlines = true, glow = true, uiFontSize = 13, editorFontSize = 13 } = {}) {
  const theme = THEMES[name] || THEMES.dracula;
  const root = document.documentElement;
  for (const [k, v] of Object.entries(theme.vars)) root.style.setProperty(`--${k}`, v);
  root.style.setProperty('--ui-font-size', `${uiFontSize}px`);
  root.style.setProperty('--editor-font-size', `${editorFontSize}px`);
  root.dataset.theme = name;
  root.dataset.mode = theme.dark ? 'dark' : 'light';
  root.dataset.scanlines = scanlines && theme.dark ? 'on' : 'off';
  root.dataset.glow = glow ? 'on' : 'off';
}
